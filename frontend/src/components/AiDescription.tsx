import { useState } from 'react'

import { describeError } from '../api/client'
import type { Impact } from '../api/types'
import type { AiDescriptionState } from '../hooks/useAiDescription'
import { AiActionButton } from './AiActionButton'
import { ErrorNote } from './Badges'
import { Markdown } from './Markdown'

const IMPACT_LABELS: Record<Impact, string> = { low: 'Low', medium: 'Medium', high: 'High' }

interface Props {
  repoId: number
  ai: AiDescriptionState
}

export function AiDescription({ repoId, ai }: Props) {
  const [open, setOpen] = useState(true)
  const { description, pending, error } = ai
  if (!description && !pending && !error) {
    return null
  }
  return (
    <section className="ai-description notice" aria-label="AI description">
      <div className="ai-description-header">
        {description ? (
          <button type="button" className="pr-description-toggle" aria-expanded={open} onClick={() => { setOpen(!open) }}>
            <span aria-hidden="true">{open ? '▾' : '▸'}</span> AI description
          </button>
        ) : (
          <span className="pr-description-toggle">AI description</span>
        )}
        {description?.outdated && (
          <span className="label warn" title="The unit changed since this description was written">
            outdated
          </span>
        )}
        {description && (
          <span className="label ai-source">
            {`AI generated by ${description.provider_label}${description.model ? ` (${description.model})` : ''}`}
          </span>
        )}
        <span className="spacer" />
        {pending ? (
          <button type="button" onClick={ai.cancel}>
            Cancel
          </button>
        ) : (
          description && <AiActionButton repoId={repoId} label="Regenerate" title="Ask the AI provider again and replace this description" onRun={(target) => { ai.run(target, true) }} />
        )}
      </div>
      {pending && (
        <p className="diff-note" role="status">
          {description ? 'Regenerating the description...' : 'Describing this unit...'}
        </p>
      )}
      {error && <ErrorNote message={describeError(error)} />}
      {description && open && (
        <div className={`pr-description-body${pending ? ' stale' : ''}`}>
          <Markdown text={description.description} />
          <p className="ai-impact">
            <strong>{`${IMPACT_LABELS[description.impact]} impact`}</strong>
            {`: ${description.impact_reason}`}
          </p>
        </div>
      )}
    </section>
  )
}
