import { QueryClient, QueryClientProvider } from '@tanstack/react-query'
import { fireEvent, render, screen, waitFor } from '@testing-library/react'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'

import type { AiStatus, Unit, UnitDescription } from '../api/types'
import { rememberAiConsent } from '../settings/aiConsent'
import { UnitCard } from './UnitCard'

const AI: AiStatus = {
  configured: true,
  provider: 'anthropic',
  label: 'Anthropic API',
  model: 'claude-opus-5-5',
  endpoint: 'https://api.anthropic.com',
  api_key_env: 'ANTHROPIC_API_KEY',
  api_key_set: true,
  problem: null,
  config_file: null,
  target: '["anthropic", "claude-opus-5-5", "https://api.anthropic.com"]',
}

const UNIT: Unit = {
  id: 7,
  revision_id: 2,
  path: 'app.py',
  old_path: null,
  module: null,
  kind: 'function',
  qualified_name: 'total',
  state: 'changed',
  change_type: 'modified',
  base_changed: false,
  approval_id: null,
  row_approvable: false,
  rows_total: 0,
  rows_approved: 0,
  binary: false,
  image: false,
  todo: true,
  action: 'approve',
  open_threads: 0,
  head_start: 1,
  head_end: 2,
}

const DESCRIBED: UnitDescription = {
  unit_id: 7,
  description: 'Adds the **tax** to the total.',
  impact: 'high',
  impact_reason: 'Changes what customers pay.',
  provider: 'anthropic',
  provider_label: 'Anthropic API',
  model: 'claude-opus-5-5',
  created_at: '2026-11-01T10:00:00Z',
  outdated: false,
}

interface Routes {
  ai?: AiStatus
  stored?: UnitDescription[]
  answer?: () => Response | null
}

function renderCard({ ai = AI, stored = [], answer = () => Response.json(DESCRIBED) }: Routes = {}) {
  let saved = stored
  let cancelRunning: () => void = () => undefined
  const fetchMock = vi.fn<(url: string, init?: RequestInit) => Promise<Response>>(async (url) => {
    if (url === '/api/repos/3/ai') {
      return Response.json(ai)
    }
    if (url === '/api/reviews/1/descriptions?revision_id=2') {
      return Response.json(saved)
    }
    if (url === '/api/reviews/1/units/7/description') {
      const response = answer()
      if (response === null) {
        return new Promise<Response>((resolve) => {
          cancelRunning = () => { resolve(Response.json({ detail: 'Cancelled' }, { status: 409 })) }
        })
      }
      if (response.ok) {
        const described = (await response.clone().json()) as UnitDescription
        saved = [...saved.filter((description) => description.unit_id !== described.unit_id), described]
      }
      return response
    }
    if (url.startsWith('/api/ai/calls/')) {
      cancelRunning()
      return Response.json({ cancelled: true })
    }
    return new Promise<Response>(() => undefined)
  })
  vi.stubGlobal('fetch', fetchMock)
  const client = new QueryClient({ defaultOptions: { queries: { retry: false } } })
  const card = (key: string) => (
    <QueryClientProvider client={client}>
      <UnitCard key={key} reviewId={1} repoId={3} unit={UNIT} focused={false} onFocus={() => undefined} register={() => undefined} />
    </QueryClientProvider>
  )
  const view = render(card('first'))
  return Object.assign(fetchMock, { remount: () => { view.rerender(card('second')) } })
}

function posted(fetchMock: ReturnType<typeof renderCard>, url: string): unknown[] {
  return fetchMock.mock.calls
    .filter(([called, init]) => called === url && init?.method === 'POST')
    .map(([, init]) => JSON.parse(typeof init?.body === 'string' ? init.body : '{}') as unknown)
}

describe('AI description on a unit card', () => {
  beforeEach(() => {
    window.localStorage.clear()
    if (AI.target) {
      rememberAiConsent(AI.target)
    }
  })

  afterEach(() => {
    vi.unstubAllGlobals()
  })

  it('describes a unit on demand and labels the result as AI generated', async () => {
    const fetchMock = renderCard()

    fireEvent.click(await screen.findByRole('button', { name: 'Describe' }))

    expect(await screen.findByText('tax')).toBeInTheDocument()
    expect(screen.getByText('AI generated by Anthropic API (claude-opus-5-5)')).toBeInTheDocument()
    expect(screen.getByText('High impact')).toBeInTheDocument()
    expect(screen.getByText(': Changes what customers pay.')).toBeInTheDocument()
    expect(screen.queryByRole('button', { name: 'Describe' })).toBeNull()
    expect(posted(fetchMock, '/api/reviews/1/units/7/description')).toEqual([{ target: AI.target, regenerate: false, call_id: expect.stringMatching(/^[0-9a-f]{32}$/) as unknown }])
  })

  it('shows the loading state and can cancel the call', async () => {
    const fetchMock = renderCard({ answer: () => null })

    fireEvent.click(await screen.findByRole('button', { name: 'Describe' }))
    expect(await screen.findByRole('status')).toHaveTextContent('Describing this unit...')
    fireEvent.click(screen.getByRole('button', { name: 'Cancel' }))

    await waitFor(() => { expect(screen.queryByRole('status')).toBeNull() })
    const [describeRequest] = posted(fetchMock, '/api/reviews/1/units/7/description') as { call_id: string }[]
    expect(fetchMock.mock.calls.map(([url]) => url)).toContain(`/api/ai/calls/${describeRequest.call_id}/cancel`)
    expect(screen.getByRole('button', { name: 'Describe' })).toBeEnabled()
  })

  it('keeps showing a running call when the card is collapsed', async () => {
    renderCard({ answer: () => null })

    fireEvent.click(await screen.findByRole('button', { name: 'Describe' }))
    await screen.findByRole('status')
    fireEvent.click(screen.getByRole('button', { name: 'Collapse unit' }))

    expect(screen.getByRole('button', { name: 'Expand unit' })).toBeInTheDocument()
    expect(screen.getByRole('status')).toHaveTextContent('Describing this unit...')
    expect(screen.getByRole('button', { name: 'Cancel' })).toBeInTheDocument()
    expect(screen.queryByRole('button', { name: 'Describe' })).toBeNull()
  })

  it('still knows about a running call after the card is mounted again', async () => {
    const fetchMock = renderCard({ answer: () => null })
    fireEvent.click(await screen.findByRole('button', { name: 'Describe' }))
    await screen.findByRole('status')

    fetchMock.remount()

    expect(await screen.findByRole('status')).toHaveTextContent('Describing this unit...')
    fireEvent.click(screen.getByRole('button', { name: 'Cancel' }))
    await waitFor(() => { expect(screen.queryByRole('status')).toBeNull() })
    expect(posted(fetchMock, '/api/reviews/1/units/7/description')).toHaveLength(1)
  })

  it('shows an error and lets the reviewer try again', async () => {
    renderCard({ answer: () => Response.json({ detail: 'No answer within 600 seconds' }, { status: 504 }) })

    fireEvent.click(await screen.findByRole('button', { name: 'Describe' }))

    expect(await screen.findByRole('alert')).toHaveTextContent('No answer within 600 seconds')
    expect(screen.getByRole('button', { name: 'Describe' })).toBeInTheDocument()
  })

  it('marks a description of an earlier version as outdated and regenerates it', async () => {
    const fetchMock = renderCard({ stored: [{ ...DESCRIBED, outdated: true }], answer: () => Response.json({ ...DESCRIBED, description: 'Applies a tax.' }) })

    expect(await screen.findByText('outdated')).toBeInTheDocument()
    fireEvent.click(await screen.findByRole('button', { name: 'Regenerate' }))

    expect(await screen.findByText('Applies a tax.')).toBeInTheDocument()
    expect(screen.queryByText('outdated')).toBeNull()
    expect(posted(fetchMock, '/api/reviews/1/units/7/description')).toEqual([{ target: AI.target, regenerate: false, call_id: expect.stringMatching(/^[0-9a-f]{32}$/) as unknown }])
  })

  it('regenerates a current description without the cached answer', async () => {
    const fetchMock = renderCard({ stored: [DESCRIBED], answer: () => Response.json({ ...DESCRIBED, description: 'Applies a tax.' }) })

    fireEvent.click(await screen.findByRole('button', { name: 'Regenerate' }))

    expect(await screen.findByText('Applies a tax.')).toBeInTheDocument()
    expect(posted(fetchMock, '/api/reviews/1/units/7/description')).toEqual([{ target: AI.target, regenerate: true, call_id: expect.stringMatching(/^[0-9a-f]{32}$/) as unknown }])
  })

  it('offers Describe only once the stored descriptions are known', async () => {
    renderCard({ stored: [DESCRIBED] })

    expect(await screen.findByText('tax')).toBeInTheDocument()
    expect(screen.queryByRole('button', { name: 'Describe' })).toBeNull()
  })

  it('can collapse the description', async () => {
    renderCard({ stored: [DESCRIBED] })

    fireEvent.click(await screen.findByRole('button', { name: /AI description/ }))

    expect(screen.queryByText('tax')).toBeNull()
    expect(screen.getByRole('button', { name: /AI description/ })).toHaveAttribute('aria-expanded', 'false')
  })

  it('offers no Describe button without a provider', async () => {
    const fetchMock = renderCard({ ai: { ...AI, configured: false, provider: null, label: null, model: null, endpoint: null, target: null } })

    await waitFor(() => { expect(fetchMock).toHaveBeenCalledWith('/api/repos/3/ai', expect.anything()) })
    await new Promise((resolve) => setTimeout(resolve, 0))

    expect(screen.queryByRole('button', { name: 'Describe' })).toBeNull()
  })
})
